from dataclasses import dataclass, field
from pathlib import Path

from fastapi.routing import APIRoute

import optscan.api.routers as routers_package
from optscan.config import REPO_ROOT, Settings
from optscan.jobs.schedule import jobs
from optscan.storage import db

SRC = REPO_ROOT / "src" / "optscan"
FRONTEND = REPO_ROOT / "frontend" / "src"
VIEWS = FRONTEND / "views"
API_CLIENT = FRONTEND / "api.js"
INDEX = REPO_ROOT / "MAP.md"
MAP_DIR = REPO_ROOT / "map"
GENERATED = MAP_DIR / "generated"
NOTES = MAP_DIR / "notes.md"

#: The prefix every API route is mounted under, left off the paths written here the
#: same way the dashboard's client leaves it off.
API_PREFIX = "/api"

HEADER = (
    "<!-- Generated by `optscan map generate` from the code. Do not edit by hand: the "
    "map test fails on any difference. -->\n\n"
)

#: Kinds where every item needs a note. A table or a scheduled job whose purpose nobody
#: wrote down is exactly the gap the map exists to close; a module already carries its
#: purpose in its docstring.
NOTE_REQUIRED = ("table", "job")

#: Imports that say nothing about wiring: wire formats, domain types, settings, logging.
#: Listing them under every route would bury the calls that matter.
QUIET_IMPORTS = (
    "optscan.api.schemas",
    "optscan.models",
    "optscan.config",
    "optscan.logging",
)

_SQL_HINT = re.compile(r"\b(?:SELECT|INSERT|UPDATE|DELETE|REPLACE)\b")
_WRITE = re.compile(
    r"\b(?:INSERT(?:\s+OR\s+\w+)?\s+INTO|REPLACE\s+INTO|UPDATE|DELETE\s+FROM)\s+(\{\?\}|\w+)"
)
_DELETE_FROM = re.compile(r"\bDELETE\s+FROM\b")
_READ = re.compile(r"\b(?:FROM|JOIN)\s+(\{\?\}|\w+)")
_PLACEHOLDER = "{?}"


def fact_hash(facts: list[str]) -> str:
    """A short hash of an item's facts: what a note is pinned to."""
    return hashlib.sha256("\n".join(facts).encode("utf-8")).hexdigest()[:12]


@dataclass(slots=True)
class Item:
    """One thing on the map, named the way notes name it: `table:daily_condition`."""

    key: str
    facts: list[str]

    @property
    def kind(self) -> str:
        return self.key.split(":", 1)[0]

    @property
    def fact_hash(self) -> str:
        return fact_hash(self.facts)


@dataclass(slots=True)
class RepoMap:
    files: dict[str, str]
    items: dict[str, Item]
    unresolved_sql: list[str] = field(default_factory=list)
    unmatched_calls: list[str] = field(default_factory=list)


def _cell(text: str) -> str:
    return text.replace("|", "\\|").replace("\n", " ").strip() or "-"


def _table(head: list[str], rows: list[list[str]]) -> str:
    lines = ["| " + " | ".join(head) + " |", "|" + "---|" * len(head)]
    lines += ["| " + " | ".join(_cell(cell) for cell in row) + " |" for row in rows]
    return "\n".join(lines) + "\n"


def _python_files() -> list[Path]:
    return [
        path
        for path in sorted(SRC.rglob("*.py"))
        if "__pycache__" not in path.parts and path.name != "__init__.py"
    ]


def _rel(path: Path) -> str:
    return path.relative_to(SRC).as_posix()


def _summary(tree: ast.Module) -> str:
    """The docstring's first sentence: the module's purpose in one line."""
    doc = ast.get_docstring(tree) or ""
    paragraph = doc.strip().split("\n\n")[0].replace("\n", " ")
    return re.split(r"(?<=[.!?])\s", paragraph, maxsplit=1)[0].strip()


# ---- modules ------------------------------------------------------------------------


def _modules(out: RepoMap) -> None:
    groups: dict[str, list[list[str]]] = defaultdict(list)
    for path in _python_files():
        module = _rel(path)
        summary = _summary(ast.parse(path.read_text(encoding="utf-8")))
        package = module.rsplit("/", 1)[0] + "/" if "/" in module else "(top level)"
        groups[package].append([f"`{module}`", summary])
        out.items[f"module:{module}"] = Item(f"module:{module}", [summary])
    parts = ["# Modules\n\nEvery module under `src/optscan`, with its docstring's first line.\n"]
    for package in sorted(groups, key=lambda name: (name != "(top level)", name)):
        parts.append(f"\n## {package}\n\n" + _table(["module", "purpose"], groups[package]))
    out.files["modules.md"] = "".join(parts)


# ---- storage ------------------------------------------------------------------------


def _tables() -> list[str]:
    with (
        tempfile.TemporaryDirectory() as folder,
        db.session(Path(folder) / "map.sqlite") as conn,
    ):
        return sorted(
            row[0]
            for row in conn.execute(
                "SELECT name FROM sqlite_master WHERE type = 'table' AND name NOT LIKE 'sqlite_%'"
            )
        )


def _docstring_ids(tree: ast.Module) -> set[int]:
    ids = set()
    for node in ast.walk(tree):
        if isinstance(node, ast.Module | ast.ClassDef | ast.FunctionDef | ast.AsyncFunctionDef):
            body = node.body
            if (
                body
                and isinstance(body[0], ast.Expr)
                and isinstance(body[0].value, ast.Constant)
                and isinstance(body[0].value.value, str)
            ):
                ids.add(id(body[0].value))
    return ids


def _strings(tree: ast.Module) -> list[str]:
    """Every string literal that is not a docstring, with f-string holes as `{?}`."""
    skip = _docstring_ids(tree)
    inside_fstrings: set[int] = set()
    out = []
    for node in ast.walk(tree):
        if isinstance(node, ast.JoinedStr):
            text = ""
            for value in node.values:
                inside_fstrings.add(id(value))
                text += value.value if isinstance(value, ast.Constant) else _PLACEHOLDER
            out.append(text)
    for node in ast.walk(tree):
        if (
            isinstance(node, ast.Constant)
            and isinstance(node.value, str)
            and id(node) not in skip
            and id(node) not in inside_fstrings
        ):
            out.append(node.value)
    return out


def _storage(out: RepoMap) -> None:
    tables = _tables()
    known = set(tables)
    writers: dict[str, set[str]] = defaultdict(set)
    readers: dict[str, set[str]] = defaultdict(set)
    unresolved: set[str] = set()
    for path in _python_files():
        module = _rel(path)
        for text in _strings(ast.parse(path.read_text(encoding="utf-8"))):
            if not _SQL_HINT.search(text):
                continue
            for pattern, target in ((_WRITE, writers), (_READ, readers)):
                scanned = _DELETE_FROM.sub("", text) if pattern is _READ else text
                for name in pattern.findall(scanned):
                    if name == _PLACEHOLDER:
                        snippet = " ".join(text.split())[:80]
                        unresolved.add(f"`{module}`: `{snippet}`")
                    elif name in known:
                        target[name].add(module)
    rows = []
    for table in tables:
        wrote = sorted(writers[table])
        read = sorted(readers[table])
        rows.append(
            [
                f"`{table}`",
                ", ".join(f"`{m}`" for m in wrote) or "none found",
                ", ".join(f"`{m}`" for m in read) or "none found",
            ]
        )
        out.items[f"table:{table}"] = Item(
            f"table:{table}", ["writers:", *wrote, "readers:", *read]
        )
    out.unresolved_sql = sorted(unresolved)
    text = (
        "# Storage\n\nEvery table the migrations create, with the modules whose SQL writes "
        "it and reads it. Found by scanning string literals for INSERT, UPDATE, DELETE, "
        "REPLACE, FROM and JOIN against the table names.\n\n"
        + _table(["table", "written by", "read by"], rows)
        + "\n## SQL the scanner could not resolve\n\nA table name built at run time. "
        "Listed so the gap is visible; the map test caps how many there may be.\n\n"
        + ("\n".join(f"- {line}" for line in out.unresolved_sql) or "None.")
        + "\n"
    )
    out.files["storage.md"] = text


# ---- routes and caches --------------------------------------------------------------


def _import_table(tree: ast.Module) -> dict[str, tuple[str, str | None]]:
    """Local name -> (optscan module path, attribute or None when it names a module)."""
    names: dict[str, tuple[str, str | None]] = {}
    for node in ast.walk(tree):
        if not isinstance(node, ast.ImportFrom) or not node.module:
            continue
        if not node.module.startswith("optscan") or node.module.startswith(QUIET_IMPORTS):
            continue
        for alias in node.names:
            local = alias.asname or alias.name
            dotted = f"{node.module}.{alias.name}"
            if _module_path(dotted):
                names[local] = (_module_path(dotted), None)
            else:
                names[local] = (_module_path(node.module) or node.module, alias.name)
    return names


def _module_path(dotted: str) -> str | None:
    """`optscan.api.deps` -> `api/deps.py`; a package -> `providers/`; else None."""
    parts = dotted.split(".")[1:]
    if not parts:
        return None
    base = SRC.joinpath(*parts)
    if base.with_suffix(".py").exists():
        return "/".join(parts) + ".py"
    if base.is_dir():
        return "/".join(parts) + "/"
    return None


def _calls(function: ast.AST, imports: dict[str, tuple[str, str | None]]) -> set[str]:
    """What a function reaches through optscan imports, as `module: name`."""
    found = set()
    for node in ast.walk(function):
        if isinstance(node, ast.Attribute) and isinstance(node.value, ast.Name):
            target = imports.get(node.value.id)
            if target and target[1] is None:
                found.add(f"{target[0]}: {node.attr}")
        elif isinstance(node, ast.Name) and isinstance(node.ctx, ast.Load):
            target = imports.get(node.id)
            if target and target[1] is not None:
                found.add(f"{target[0]}: {target[1]}")
    return found


def _reach(tree: ast.Module, start: str, imports) -> set[str]:
    """Calls from a function and every same-module function it calls, transitively."""
    functions = {
        node.name: node
        for node in tree.body
        if isinstance(node, ast.FunctionDef | ast.AsyncFunctionDef)
    }
    seen, queue, found = {start}, [start], set()
    while queue:
        function = functions[queue.pop()]
        local = {**imports, **_import_table(function)}
        body = ast.Module(body=function.body + function.args.defaults, type_ignores=[])
        found |= _calls(body, local)
        for node in ast.walk(body):
            if isinstance(node, ast.Name) and node.id in functions and node.id not in seen:
                seen.add(node.id)
                queue.append(node.id)
    return found


def _group_calls(calls: set[str]) -> list[str]:
    by_module: dict[str, list[str]] = defaultdict(list)
    for call in calls:
        module, name = call.split(": ", 1)
        by_module[module].append(name)
    return [f"{module}: {', '.join(sorted(names))}" for module, names in sorted(by_module.items())]


@dataclass(slots=True)
class _Route:
    path: str
    methods: set[str]
    router: str
    uses: set[str]


def _routes() -> dict[str, _Route]:
    package = routers_package
    routes: dict[str, _Route] = {}
    for info in sorted(pkgutil.iter_modules(package.__path__), key=lambda i: i.name):
        module = importlib.import_module(f"{package.__name__}.{info.name}")
        router = getattr(module, "router", None)
        if router is None:
            continue
        tree = ast.parse(inspect.getsource(module))
        imports = _import_table(tree)
        for route in router.routes:
            if not isinstance(route, APIRoute):
                continue
            entry = routes.setdefault(
                route.path, _Route(route.path, set(), f"api/routers/{info.name}.py", set())
            )
            entry.methods |= set(route.methods)
            entry.uses |= _reach(tree, route.endpoint.__name__, imports)
    return routes


def _caches() -> list[list[str]]:
    path = SRC / "api" / "deps.py"
    tree = ast.parse(path.read_text(encoding="utf-8"))
    constants = {
        node.targets[0].id: ast.unparse(node.value)
        for node in tree.body
        if isinstance(node, ast.Assign)
        and len(node.targets) == 1
        and isinstance(node.targets[0], ast.Name)
    }
    caches = {
        node.targets[0].id: ast.unparse(node.value.args[0]) if node.value.args else ""
        for node in tree.body
        if isinstance(node, ast.Assign)
        and isinstance(node.value, ast.Call)
        and isinstance(node.value.func, ast.Name)
        and node.value.func.id == "_TimedCache"
    }
    put_in: dict[str, set[str]] = defaultdict(set)
    ttls: dict[str, set[str]] = defaultdict(set)
    cleared: dict[str, set[str]] = defaultdict(set)
    for function in tree.body:
        if not isinstance(function, ast.FunctionDef):
            continue
        ttl_names = {
            node.id
            for node in ast.walk(function)
            if isinstance(node, ast.Name) and node.id.endswith("_TTL_SECONDS")
        }
        for node in ast.walk(function):
            if (
                isinstance(node, ast.Call)
                and isinstance(node.func, ast.Attribute)
                and isinstance(node.func.value, ast.Name)
                and node.func.value.id in caches
            ):
                cache = node.func.value.id
                if node.func.attr == "put":
                    put_in[cache].add(function.name)
                    ttls[cache] |= {f"{name} = {constants.get(name, '?')} s" for name in ttl_names}
                elif node.func.attr == "clear":
                    cleared[cache].add(function.name)
    rows = []
    for cache in sorted(caches):
        rows.append(
            [
                f"`{cache}`",
                caches[cache],
                ", ".join(sorted(ttls[cache])) or "none (until replaced)",
                ", ".join(f"`{name}`" for name in sorted(put_in[cache])) or "-",
                ", ".join(f"`{name}`" for name in sorted(cleared[cache])) or "-",
            ]
        )
    return rows


# ---- the dashboard ------------------------------------------------------------------


def _template_path(text: str, start: int) -> str:
    """Read a string or template literal from `start` (its opening quote), as a path.

    `${query(...)}` drops out and any other `${...}` becomes `{}`, so the result
    compares with a route path whose parameters are normalised the same way.
    """
    quote = text[start]
    index, path = start + 1, ""
    while index < len(text) and text[index] != quote:
        if text.startswith("${", index):
            depth, end = 1, index + 2
            while depth:
                depth += {"{": 1, "}": -1}.get(text[end], 0)
                end += 1
            inner = text[index + 2 : end - 1]
            if inner != "BASE" and not inner.startswith("query("):
                path += "{}"
            index = end
            continue
        path += text[index]
        index += 1
    return path


def _client() -> dict[str, tuple[str, str]]:
    """The dashboard's API client: function name -> (method, normalised path)."""
    text = API_CLIENT.read_text(encoding="utf-8")
    body = text[text.index("export const api = {") :]
    starts = [(m.start(), m.group(1)) for m in re.finditer(r"^  (\w+): ", body, re.M)]
    functions = {}
    for index, (offset, name) in enumerate(starts):
        end = starts[index + 1][0] if index + 1 < len(starts) else len(body)
        entry = body[offset:end]
        literal = re.search(r"[`\"](?=/|\$\{BASE\}/)", entry)
        if literal is None:
            continue
        method = re.search(r"method:\s*\"(\w+)\"", entry)
        functions[name] = (
            method.group(1) if method else "GET",
            _template_path(entry, literal.start()),
        )
    return functions


def _normalise(path: str) -> str:
    return re.sub(r"\{[^}]*\}", "{}", path)


#: `api.chain(` and the chained form `api\n  .chain(`; never the `./api.js` import path.
_CLIENT_CALL = re.compile(r"(?<![\w/.])api\s*\.\s*(\w+)")
#: A route reached without the client, such as the EventSource in live.js.
_DIRECT = re.compile(r"[\"`]" + API_PREFIX + r"(/[^\"`$?]*)")
DIRECT_PREFIX = "fetch "


def _callers() -> dict[str, list[str]]:
    """Each frontend file that calls the API -> the client functions it calls.

    A route fetched directly, without the client, appears as `fetch /path`.
    """
    out = {}
    for path in sorted(FRONTEND.rglob("*")):
        if path.suffix not in (".js", ".jsx") or path == API_CLIENT:
            continue
        source = path.read_text(encoding="utf-8")
        names = sorted(
            set(_CLIENT_CALL.findall(source))
            | {DIRECT_PREFIX + direct for direct in _DIRECT.findall(source)}
        )
        relative = path.relative_to(FRONTEND).with_suffix("").as_posix()
        name = relative.removeprefix("views/")
        if names or path.parent == VIEWS:
            out[name] = names
    return out


def _dashboard(out: RepoMap) -> None:
    routes = _routes()
    callers = _callers()
    client = _client()
    for names in callers.values():
        for name in names:
            if name.startswith(DIRECT_PREFIX):
                client[name] = ("GET", name.removeprefix(DIRECT_PREFIX))
    by_endpoint: dict[tuple[str, str], list[str]] = defaultdict(list)
    for name, (method, path) in client.items():
        by_endpoint[(method, _normalise(path))].append(name)
    route_keys = {
        (method, _normalise(path.removeprefix(API_PREFIX)))
        for path, route in routes.items()
        for method in route.methods
    }
    out.unmatched_calls = sorted(
        f"`api.{name}` -> {method} `{path}`"
        for name, (method, path) in client.items()
        if (method, _normalise(path)) not in route_keys
    )

    route_rows = []
    for path in sorted(routes):
        route = routes[path]
        short = path.removeprefix(API_PREFIX)
        methods = sorted(route.methods - {"HEAD"})
        functions = sorted(
            {name for m in methods for name in by_endpoint.get((m, _normalise(short)), [])}
        )
        called_by = sorted(
            caller for caller, names in callers.items() if set(names) & set(functions)
        )
        uses = _group_calls(route.uses)
        route_rows.append(
            [
                f"`{short}`",
                " ".join(methods),
                f"`{route.router}`",
                "; ".join(uses) or "-",
                ", ".join(f"`{c}`" for c in called_by) or "-",
            ]
        )
        out.items[f"route:{short}"] = Item(
            f"route:{short}", [*methods, route.router, *uses, "callers:", *called_by]
        )

    caches = _caches()
    for row in caches:
        name = row[0].strip("`")
        out.items[f"cache:{name}"] = Item(f"cache:{name}", row[1:])

    out.files["routes.md"] = (
        "# HTTP routes and caches\n\nEvery route, all under `/api`. *Uses* is what the "
        "endpoint reaches through optscan imports, following helper functions in the same "
        "router; *called by* is every dashboard file whose client calls hit it.\n\n"
        + _table(["route", "methods", "router", "uses", "called by"], route_rows)
        + "\n## Caches in `api/deps.py`\n\nEach `_TimedCache`, the TTL constants used where "
        "it is filled, and the functions that clear it.\n\n"
        + _table(["cache", "capacity", "TTL", "filled in", "cleared by"], caches)
    )

    view_rows = []
    for caller in sorted(callers):
        names = callers[caller]
        hits = [f"`{n}` ({' '.join(client[n])})" if n in client else f"`{n}`" for n in names]
        view_rows.append([f"`{caller}`", ", ".join(hits) or "none (composes other views)"])
        out.items[f"view:{caller}"] = Item(
            f"view:{caller}", [f"{n} {' '.join(client.get(n, ('?', '?')))}" for n in names]
        )
    called = {name for names in callers.values() for name in names}
    unused = sorted(f"`api.{name}`" for name in client if name not in called)
    out.files["views.md"] = (
        "# Dashboard views\n\nEvery file under `frontend/src/views`, and any other frontend "
        "file that calls the API client (`frontend/src/api.js`, the only HTTP client), "
        "with the client functions it calls and their method and path.\n\n"
        + _table(["file", "calls"], view_rows)
        + "\n## Client calls that match no route\n\n"
        + ("\n".join(f"- {line}" for line in out.unmatched_calls) or "None.")
        + "\n\n## Client functions no file calls\n\n"
        + (", ".join(unused) or "None.")
        + "\n"
    )


# ---- schedule and commands ----------------------------------------------------------


def _schedule(out: RepoMap) -> None:
    # model_construct takes the declared defaults and reads no environment, so the times
    # here are the shipped ones on every machine, not whatever this one overrides.
    settings = Settings.model_construct()
    rows = []
    for job in jobs(settings):
        repeats = (
            f"every {job.repeat_minutes} min for {job.repeat_for_minutes} min"
            if job.repeat_minutes
            else "once"
        )
        runs = "optscan " + job.arguments.removeprefix("-m optscan ").strip()
        facts = [
            job.at.strftime("%H:%M"),
            repeats,
            f"default install {job.default_install}",
            f"trading days only {job.trading_days_only}",
            runs,
        ]
        rows.append(
            [
                f"`{job.key}`",
                facts[0],
                repeats,
                "yes" if job.default_install else "no",
                "yes" if job.trading_days_only else "no",
                f"`{runs}`",
            ]
        )
        out.items[f"job:{job.key}"] = Item(f"job:{job.key}", facts)
    out.files["schedule.md"] = (
        "# Scheduled jobs\n\nFrom `jobs/schedule.py` `jobs()`, at the shipped default times "
        "(market time). The user installs them with `optscan schedule --install`.\n\n"
        + _table(["job", "at", "repeats", "default install", "trading days only", "runs"], rows)
    )


def _commands(out: RepoMap) -> None:
    tree = ast.parse((SRC / "cli.py").read_text(encoding="utf-8"))
    main = next(n for n in tree.body if isinstance(n, ast.FunctionDef) and n.name == "main")
    handlers = next(
        node.value
        for node in ast.walk(main)
        if isinstance(node, ast.Assign)
        and isinstance(node.targets[0], ast.Name)
        and node.targets[0].id == "handlers"
    )
    functions = {n.name: n for n in tree.body if isinstance(n, ast.FunctionDef)}
    rows = []
    for key, value in zip(handlers.keys, handlers.values, strict=True):
        command, handler = key.value, value.id
        modules, seen, queue = set(), {handler}, [handler]
        while queue:
            function = functions[queue.pop()]
            for node in ast.walk(function):
                if isinstance(node, ast.ImportFrom) and node.module:
                    if node.module.startswith("optscan") and not node.module.startswith(
                        QUIET_IMPORTS
                    ):
                        for alias in node.names:
                            path = _module_path(f"{node.module}.{alias.name}")
                            modules.add(path or _module_path(node.module) or node.module)
                elif isinstance(node, ast.Name) and node.id in functions and node.id not in seen:
                    seen.add(node.id)
                    queue.append(node.id)
        found = sorted(modules)
        rows.append([f"`{command}`", f"`{handler}`", ", ".join(f"`{m}`" for m in found) or "-"])
        out.items[f"command:{command}"] = Item(f"command:{command}", [handler, *found])
    rows.sort()
    out.files["commands.md"] = (
        "# Commands\n\nEvery `optscan` command, its handler in `cli.py`, and the modules the "
        "handler imports (following the helpers it calls in `cli.py`).\n\n"
        + _table(["command", "handler", "imports"], rows)
    )


def generate() -> RepoMap:
    """Build every generated file and item from the code, in memory."""
    out = RepoMap(files={}, items={})
    _modules(out)
    _storage(out)
    _dashboard(out)
    _schedule(out)
    _commands(out)
    out.files = {name: HEADER + text for name, text in sorted(out.files.items())}
    return out


def write(repo_map: RepoMap) -> list[str]:
    """Write the generated files; returns the names that changed."""
    GENERATED.mkdir(parents=True, exist_ok=True)
    changed = []
    for name, text in repo_map.files.items():
        path = GENERATED / name
        if not path.exists() or path.read_text(encoding="utf-8") != text:
            path.write_text(text, encoding="utf-8", newline="\n")
            changed.append(name)
    for stray in GENERATED.glob("*.md"):
        if stray.name not in repo_map.files:
            stray.unlink()
            changed.append(stray.name)
    return changed


# ---- notes --------------------------------------------------------------------------


@dataclass(slots=True)
class Note:
    key: str
    fact: str | None
    test: str | None
    body: str


_NOTE_HEAD = re.compile(r"^### (\S+)[ \t]*$", re.M)


def load_notes(text: str | None = None) -> list[Note]:
    """Parse `map/notes.md`: `### key`, then `fact: <hash>` or `test: <file>::<name>`."""
    if text is None:
        text = NOTES.read_text(encoding="utf-8")
    heads = list(_NOTE_HEAD.finditer(text))
    notes = []
    for index, head in enumerate(heads):
        end = heads[index + 1].start() if index + 1 < len(heads) else len(text)
        block = text[head.end() : end]
        fact = re.search(r"^fact: (\w+)\s*$", block, re.M)
        test = re.search(r"^test: (\S+)\s*$", block, re.M)
        notes.append(
            Note(
                key=head.group(1),
                fact=fact.group(1) if fact else None,
                test=test.group(1) if test else None,
                body=textwrap.dedent(block).strip(),
            )
        )
    return notes


def stamp(keys: list[str], repo_map: RepoMap, *, every: bool = False) -> list[str]:
    """Rewrite the fact hash of the named notes (or all of them) to the current one."""
    text = NOTES.read_text(encoding="utf-8")
    stamped = []
    for note in load_notes(text):
        if not (every or note.key in keys) or note.key not in repo_map.items:
            continue
        current = repo_map.items[note.key].fact_hash
        if note.fact == current:
            continue
        heading = f"### {note.key}\n"
        at = text.index(heading) + len(heading)
        following = _NOTE_HEAD.search(text, at)
        end = following.start() if following else len(text)
        block = text[at:end]
        if re.search(r"^fact:", block, re.M):
            block = re.sub(r"^fact:[^\n]*$", f"fact: {current}", block, count=1, flags=re.M)
        else:
            block = f"fact: {current}\n" + block
        text = text[:at] + block + text[end:]
        stamped.append(note.key)
    NOTES.write_text(text, encoding="utf-8", newline="\n")
    return stamped


def problems(repo_map: RepoMap, notes: list[Note]) -> dict[str, list[str]]:
    """Everything the map test checks about the notes, by check."""
    items = repo_map.items
    keyed = {note.key: note for note in notes}
    return {
        "missing": sorted(
            key for key, item in items.items() if item.kind in NOTE_REQUIRED and key not in keyed
        ),
        "dead": sorted(note.key for note in notes if note.test is None and note.key not in items),
        "stale": sorted(
            note.key
            for note in notes
            if note.key in items and note.fact != items[note.key].fact_hash
        ),
        "unpinned": sorted(note.key for note in notes if note.fact is None and note.test is None),
    }
