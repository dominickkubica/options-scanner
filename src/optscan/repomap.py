"""The generated half of the wiring map: facts read from the code, never typed.

`optscan map generate` writes one Markdown file per section into `map/generated/`. Every
fact in them is extracted, not remembered: modules and their docstrings from the source
tree, tables from the migrations and their writers and readers from the SQL that names
them, routes and what each endpoint calls from the routers, the dashboard's calls from
its API client, jobs from the schedule, and commands from the CLI's handlers.
`tests/test_map.py` regenerates in memory and fails on any difference, so a committed
fact cannot disagree with the code.

What a machine cannot know -- why a table exists, what a lookup has cost before -- lives
in `map/notes.md`, one entry per item, pinned to a hash of that item's facts here. The
hash is taken over the item's wiring, not its file: an unrelated edit to a module leaves
its notes alone, while a new writer or a dropped reader changes the hash, and the note
fails until someone re-reads it and runs `optscan map stamp <key>`.

Reads the repository, never `data/`. Nothing in the running app imports it.
"""

from __future__ import annotations

import ast
import hashlib
import importlib
import inspect
import pkgutil
import re
import tempfile
import textwrap
