"""The wiring map has to match the code, both ways, and its notes have to be current.

The facts half of the map is generated by `optscan.repomap` into `map/generated/`, so the
first check is simply that the committed files are what the code produces today. A new
module, table, route, view, job or command appears there without anyone remembering it,
and a deleted one disappears.

The notes half in `map/notes.md` is written by people. Each note is pinned to a hash of
its item's facts, so a note whose item has been rewired fails here until someone re-reads
it and runs `optscan map stamp <key>`. Every table and job must have one, every note must
name something that exists, and every trap must name a test that exists.

What this cannot check is whether a note's prose is true. It can only make sure someone
looks at it again whenever the wiring under it changes.
"""

from __future__ import annotations

import re

import pytest

from optscan import repomap
from optscan.config import REPO_ROOT, Settings

#: Byte budgets for the hand-written files, the ones a session reads by default. Over
#: budget, move detail to DECISIONS.md or a docstring rather than raising the number.
INDEX_BUDGET = 6 * 1024
NOTES_BUDGET = 10 * 1024

#: How many SQL strings may name their table at run time before the scanner's view of
#: who writes and reads what is too incomplete to trust.
UNRESOLVED_SQL_BUDGET = 0


@pytest.fixture(scope="module")
def repo_map() -> repomap.RepoMap:
    return repomap.generate()


@pytest.fixture(scope="module")
def notes() -> list[repomap.Note]:
    return repomap.load_notes()


def test_generated_files_match_the_code(repo_map: repomap.RepoMap) -> None:
    stale = [
        name
        for name, text in repo_map.files.items()
        if not (repomap.GENERATED / name).exists()
        or (repomap.GENERATED / name).read_text(encoding="utf-8") != text
    ]
    stray = sorted(
        path.name for path in repomap.GENERATED.glob("*.md") if path.name not in repo_map.files
    )
    assert not stale and not stray, (
        f"map/generated is out of date ({stale + stray}). Run `optscan map generate` and "
        "commit the result with the change."
    )


def test_every_route_the_app_serves_is_generated(repo_map: repomap.RepoMap, tmp_path) -> None:
    """The generator reads the routers; this reads the app, so a route mounted any other
    way cannot hide from the map."""
    from optscan.api.app import create_app

    app = create_app(Settings(_env_file=None, data_dir=tmp_path))
    served = {path.removeprefix(repomap.API_PREFIX) for path in app.openapi()["paths"]}
    generated = {key.removeprefix("route:") for key in repo_map.items if key.startswith("route:")}
    assert served == generated


def test_every_table_and_job_has_a_note(repo_map, notes) -> None:
    missing = repomap.problems(repo_map, notes)["missing"]
    assert not missing, (
        f"No note in map/notes.md for: {missing}. Say what it holds or does and why, "
        "then `optscan map stamp <key>`."
    )


def test_every_note_names_something_that_exists(repo_map, notes) -> None:
    dead = repomap.problems(repo_map, notes)["dead"]
    assert not dead, f"Notes for items that no longer exist: {dead}. Delete or re-key them."


def test_every_note_is_pinned(repo_map, notes) -> None:
    unpinned = repomap.problems(repo_map, notes)["unpinned"]
    assert not unpinned, f"Notes with neither `fact:` nor `test:`: {unpinned}"


def test_notes_are_current_with_their_wiring(repo_map, notes) -> None:
    stale = repomap.problems(repo_map, notes)["stale"]
    assert not stale, (
        f"The wiring under these notes changed: {stale}. Re-read each against "
        "map/generated, fix it if it is wrong, then `optscan map stamp <key>`."
    )


def test_every_trap_names_a_test_that_exists(notes) -> None:
    broken = []
    for note in notes:
        if not note.key.startswith("trap:"):
            continue
        assert note.test, f"{note.key} needs `test: <file>::<name>` or `test: none`"
        if note.test == "none":
            continue
        file, _, name = note.test.partition("::")
        path = REPO_ROOT / file
        if not path.exists() or not re.search(
            rf"^def {re.escape(name)}\(", path.read_text(encoding="utf-8"), re.M
        ):
            broken.append(f"{note.key} -> {note.test}")
    assert not broken, f"Traps pointing at tests that do not exist: {broken}"


def _named_paths(text: str) -> set[str]:
    return set(re.findall(r"`([\w./-]+\.(?:py|md|jsx|js|ps1|yaml|toml))`", text))


def test_every_path_the_hand_written_files_name_exists() -> None:
    """The reverse direction for prose: a renamed or deleted file cannot linger."""
    roots = [
        REPO_ROOT,
        REPO_ROOT / "src" / "optscan",
        REPO_ROOT / "frontend" / "src",
    ]
    text = repomap.INDEX.read_text(encoding="utf-8") + repomap.NOTES.read_text(encoding="utf-8")
    missing = sorted(
        path for path in _named_paths(text) if not any((root / path).exists() for root in roots)
    )
    assert not missing, f"MAP.md or map/notes.md names files that do not exist: {missing}"


def test_the_index_points_at_every_generated_file(repo_map) -> None:
    index = repomap.INDEX.read_text(encoding="utf-8")
    missing = [name for name in repo_map.files if f"`map/generated/{name}`" not in index]
    assert not missing, f"MAP.md does not say which question {missing} answers"


def test_hand_written_files_stay_inside_their_budget() -> None:
    index = repomap.INDEX.stat().st_size
    notes = repomap.NOTES.stat().st_size
    assert index <= INDEX_BUDGET, f"MAP.md is {index} bytes, budget {INDEX_BUDGET}"
    assert notes <= NOTES_BUDGET, f"map/notes.md is {notes} bytes, budget {NOTES_BUDGET}"


def test_the_sql_scanner_sees_every_table_name(repo_map) -> None:
    assert len(repo_map.unresolved_sql) <= UNRESOLVED_SQL_BUDGET, repo_map.unresolved_sql


def test_every_dashboard_call_reaches_a_route(repo_map) -> None:
    assert not repo_map.unmatched_calls, repo_map.unmatched_calls


def test_the_map_says_how_to_keep_it_current() -> None:
    """The rule has to live in the file it governs, where the next editor will see it."""
    index = repomap.INDEX.read_text(encoding="utf-8")
    assert "Keep it current" in index
    assert "optscan map generate" in index
    assert "tests/test_map.py" in index
